// Generates src/data/image-placeholders.ts (tiny blurDataURLs for every public/images/**/*.webp).
// Run after changing images: npx tsx scripts/images/placeholders.ts
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import sharp from 'sharp';

const ROOT = process.cwd();
const IMAGES_DIR = path.join(ROOT, 'public/images');
const OUT = path.join(ROOT, 'src/data/image-placeholders.ts');

function listWebp(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return listWebp(full);
    return entry.name.endsWith('.webp') ? [full] : [];
  });
}

async function main() {
  const lines: string[] = [];
  for (const file of listWebp(IMAGES_DIR).sort()) {
    const buffer = await sharp(file).resize(8).webp({ quality: 40 }).toBuffer();
    const src =
      '/' +
      path.relative(path.join(ROOT, 'public'), file).split(path.sep).join('/');
    lines.push(
      `  '${src}': 'data:image/webp;base64,${buffer.toString('base64')}',`,
    );
  }

  writeFileSync(
    OUT,
    `// Generated by scripts/images/placeholders.ts. Do not edit by hand.\n` +
      `export const imagePlaceholders: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
  );
  console.log(`${lines.length} placeholders written`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
